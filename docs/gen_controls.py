"""Generate docs/CONTROLS.md (control -> checks matrix) from the check registry and the default policy."""
import sys, yaml
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from mcpeval.checks import load_all_checks
from mcpeval.checks.base import all_checks
from mcpeval.policy.loader import DEFAULT_POLICY

load_all_checks()
policy = yaml.safe_load(DEFAULT_POLICY.read_text())
checks = all_checks()
by_control = {}
for c in checks:
    for ctl in c.controls:
        by_control.setdefault(ctl, []).append(c)
lines = ["# Controls to checks", "", "Generated by `python docs/gen_controls.py`. Control IDs come from the AppSec best-practices document (BP-*) plus four cross-cutting controls (SEC-*).", ""]
lines += ["| Control | Title | Checks | Lane(s) |", "|---|---|---|---|"]
for ctl, meta in policy["controls"].items():
    cs = by_control.get(ctl, [])
    lines.append(f"| `{ctl}` | {meta['title']} | {', '.join(f'`{c.id}`' for c in cs) or '*(manual / runtime gateway)*'} | {', '.join(sorted({c.lane.value for c in cs}))} |")
lines += ["", "## Check catalogue", "", "| Check | Title | Default severity | Lane | Controls | Mappings |", "|---|---|---|---|---|---|"]
for c in checks:
    maps = "; ".join(f"{k}: {', '.join(v)}" for k, v in c.mappings.items())
    lines.append(f"| `{c.id}` | {c.title} | {c.default_severity.value} | {c.lane.value} | {', '.join(c.controls)} | {maps} |")
lines += ["", "Discovery-lane checks (`SHADOW-001..004`, `SHADOW-AWS`) are emitted by `mcpeval discover` and map to `SEC-SHADOW`, `SEC-SECRETS`, `BP-SIGNED`, `BP-NON-ROOT`."]
Path(__file__).with_name("CONTROLS.md").write_text("\n".join(lines) + "\n")
print(f"{len(checks)} checks, {len(by_control)} controls covered")
